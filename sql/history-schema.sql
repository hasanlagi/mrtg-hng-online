CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 password_version INT UNSIGNED NOT NULL DEFAULT 1,
 enabled TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS auth_limiter (
 fingerprint CHAR(64) PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 last_attempt BIGINT NOT NULL DEFAULT 0,
 blocked_until BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ping_state (
 router_id INT UNSIGNED NOT NULL,
 target_id TINYINT UNSIGNED NOT NULL,
 router_name VARCHAR(100) NOT NULL,
 router_host VARCHAR(255) NOT NULL,
 last_probe_at BIGINT NOT NULL DEFAULT 0,
 last_status VARCHAR(7) NOT NULL DEFAULT 'UNKNOWN',
 last_ms DOUBLE NULL,
 last_error VARCHAR(120) NULL,
 open_outage_id BIGINT UNSIGNED NULL,
 PRIMARY KEY (router_id,target_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ping_samples (
 router_id INT UNSIGNED NOT NULL,
 target_id TINYINT UNSIGNED NOT NULL,
 ts BIGINT NOT NULL,
 status VARCHAR(7) NOT NULL,
 ms DOUBLE NULL,
 PRIMARY KEY (router_id,target_id,ts)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ping_outages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 router_id INT UNSIGNED NOT NULL,
 target_id TINYINT UNSIGNED NOT NULL,
 started_at BIGINT NOT NULL,
 recovered_at BIGINT NULL,
 last_offline_at BIGINT NOT NULL,
 partial_start TINYINT NOT NULL DEFAULT 0,
 uncertain TINYINT NOT NULL DEFAULT 0,
 INDEX target_start(router_id,target_id,started_at)
) ENGINE=InnoDB;
